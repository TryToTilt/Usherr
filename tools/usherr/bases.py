"""Usherr: writes web/src/usherr-bases.css, the main colours.

A main colour tints the whole app (the page, the panels, the cards and, in
Neu, the raised and pressed surfaces) under whichever highlight colour is
picked. Each is a hue and a strength, kept low so the posters stay the
brightest thing on the page; the dark and light looks come from the same pair.
Without one the page keeps the highlight colour's own tint. The list of names
is kept in step with web/src/components/BaseChoice.tsx.

    python tools/usherr/bases.py
"""

import os

# id: (hue, strength 0-100, swatch)
BASES = {
    'navy': (222, 42, '#1b2540'),
    'espresso': (24, 24, '#2e2520'),
    'forest': (150, 20, '#1f2d26'),
    'plum': (280, 24, '#2c2336'),
    'oxblood': (350, 30, '#321e24'),
    'ocean': (196, 34, '#1b2e37'),
    'stone': (40, 7, '#2c2b27'),
}


def hsl(h, s, l):
    return f'hsl({h} {round(s)}% {round(l)}%)'


def block(bid, h, s):
    q = s / 100
    dark = f"""\
:root[data-base][data-base='{bid}']:not([data-theme='light']) {{
  --u-noir: {hsl(h, 40 * q + 8, 5)};
  --bg: {hsl(h, 40 * q + 8, 6)};
  --surface: {hsl(h, 36 * q + 8, 9)};
  --surface-2: {hsl(h, 32 * q + 8, 13)};
  --border: {hsl(h, 28 * q + 6, 20)};
  --panel-top: {hsl(h, 36 * q + 8, 14)};
  --panel-bottom: {hsl(h, 36 * q + 8, 9)};
  --n-bg: {hsl(h, 50 * q + 6, 14)};
  --n-hi: {hsl(h, 48 * q + 6, 24)};
  --n-lo: {hsl(h, 50 * q + 6, 5)};
  --n-well: {hsl(h, 50 * q + 6, 12)};
}}
"""
    light = f"""\
:root[data-base][data-base='{bid}'][data-theme='light'] {{
  --bg: {hsl(h, 40 * q + 6, 94)};
  --surface: {hsl(h, 50 * q + 6, 98)};
  --surface-2: {hsl(h, 36 * q + 6, 90)};
  --border: {hsl(h, 28 * q + 6, 82)};
  --panel-top: {hsl(h, 50 * q + 6, 98)};
  --panel-bottom: {hsl(h, 36 * q + 6, 93)};
  --n-bg: {hsl(h, 50 * q + 8, 91)};
  --n-hi: {hsl(h, 60 * q + 10, 99)};
  --n-lo: {hsl(h, 30 * q + 8, 71)};
  --n-well: {hsl(h, 46 * q + 8, 88)};
}}
"""
    return dark + light


OLED = """\
/* OLED: true black (and plain white), any highlight */
:root[data-base][data-base='oled']:not([data-theme='light']) {
  --u-noir: #000;
  --bg: #000;
  --surface: #0b0b0d;
  --surface-2: #141417;
  --border: #26262b;
  --panel-top: #0e0e11;
  --panel-bottom: #000;
  --n-bg: #000;
  --n-hi: #222227;
  --n-lo: #000;
  --n-well: #060607;
  --n-drop: rgba(0, 0, 0, 0.9);
}
:root[data-base][data-base='oled'][data-theme='light'] {
  --bg: #fff;
  --surface: #fff;
  --surface-2: #f1f1f3;
  --border: #dcdce0;
  --panel-top: #fff;
  --panel-bottom: #f7f7f8;
  --n-bg: #f4f4f6;
  --n-hi: #fff;
  --n-lo: #c4c4cb;
  --n-well: #ececef;
}
"""


def main():
    out = [
        '/* Generated by tools/usherr/bases.py: edit that, not this. The main\n'
        '   colours (Settings → General; BaseChoice.tsx), over the highlight colour. */\n'
    ]
    for bid, (h, s, _) in BASES.items():
        out.append(block(bid, h, s))
    out.append(OLED)
    # the swatch: the dark look and the light one, split corner to corner
    sw = []
    for bid, (h, s, dark) in BASES.items():
        sw.append(f'.base-swatch-{bid} {{ background: linear-gradient(135deg, {dark} 50%, {hsl(h, 50 * s / 100 + 8, 86)} 50%); }}')
    sw.append('.base-swatch-oled { background: linear-gradient(135deg, #000 50%, #fff 50%); }')
    sw.append('.base-swatch-palette { background: linear-gradient(135deg, var(--accent) 50%, var(--surface-2) 50%); }')
    sw.append('.palette-swatch[class*="base-swatch-"] { width: 14px; height: 14px; vertical-align: -2px; }')
    out.append('\n'.join(sw) + '\n')
    root = os.path.join(os.path.dirname(__file__), '..', '..')
    with open(os.path.join(root, 'web', 'src', 'usherr-bases.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
