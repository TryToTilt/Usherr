"""Usherr: writes web/src/usherr-palettes.css, the colour choices besides wine.

Every palette is a hue and a strength, turned into the same set of tokens for
dark and light, so they all keep the same contrast as one another. Wine, the
brand's own, is hand-tuned in usherr-theme.css and isn't listed here. The list
of names is kept in step with web/src/components/PaletteChoice.tsx.

    python tools/usherr/palettes.py
"""

import os

# id: (hue, strength 0-100)
PALETTES = {
    'cherry': (352, 72),
    'amber': (28, 78),
    'emerald': (152, 55),
    'teal': (184, 62),
    'blue': (214, 68),
    'violet': (264, 52),
    'rose': (328, 58),
    'graphite': (220, 10),
}


def hsl(h, s, l):
    return f'hsl({h} {round(s)}% {round(l)}%)'


def block(pid, h, s):
    k = s / 100
    dark = {
        '--u-noir': hsl(h, 50 * k, 5),
        '--u-wine': hsl(h, 70 * k, 14),
        '--u-burgundy': hsl(h, 65 * k, 33),
        '--u-burgundy-hover': hsl(h, 65 * k, 40),
        '--u-cream': hsl(h, 60 * k, 95),
        '--bg': hsl(h, 50 * k, 5),
        '--surface': hsl(h, 45 * k, 8),
        '--surface-2': hsl(h, 45 * k, 12),
        '--border': hsl(h, 40 * k, 19),
        '--text': hsl(h, 60 * k, 95),
        '--text-dim': hsl(h, 25 * k, 82),
        '--text-faint': hsl(h, 15 * k, 62),
        '--accent': hsl(h, 20 + 70 * k, 75),
        '--accent-hover': hsl(h, 20 + 70 * k, 82),
        '--accent-pressed': hsl(h, 20 + 60 * k, 66),
        '--accent-subtle': f'hsl({h} {round(20 + 70 * k)}% 75% / 0.13)',
        '--on-accent': hsl(h, 70 * k, 8),
        '--c-discover': 'var(--accent)',
        '--c-calendar': 'var(--accent)',
        '--c-tv': 'var(--accent)',
        '--on-sec': hsl(h, 70 * k, 8),
        '--on-kind': hsl(h, 70 * k, 8),
        '--panel-top': hsl(h, 60 * k, 13),
        '--panel-bottom': hsl(h, 60 * k, 8),
    }
    light = {
        '--u-cream': '#ffffff',
        '--bg': hsl(h, 40 * k, 96),
        '--surface': hsl(h, 60 * k, 99),
        '--surface-2': hsl(h, 40 * k, 92),
        '--border': hsl(h, 30 * k, 84),
        '--text': hsl(h, 60 * k, 12),
        '--text-dim': hsl(h, 25 * k, 32),
        '--text-faint': hsl(h, 15 * k, 45),
        '--accent': hsl(h, 65 * k, 33),
        '--accent-hover': hsl(h, 65 * k, 27),
        '--accent-pressed': hsl(h, 65 * k, 22),
        '--accent-subtle': f'hsl({h} {round(65 * k)}% 33% / 0.1)',
        '--on-accent': '#ffffff',
        '--c-discover': 'var(--accent)',
        '--c-calendar': 'var(--accent)',
        '--c-tv': 'var(--accent)',
        '--on-sec': '#ffffff',
        '--on-kind': '#ffffff',
        '--panel-top': hsl(h, 60 * k, 99),
        '--panel-bottom': hsl(h, 40 * k, 95),
    }
    out = [f":root[data-palette='{pid}'] {{"]
    out += [f'  {n}: {v};' for n, v in dark.items()]
    out += ['}', f":root[data-palette='{pid}'][data-theme='light'] {{"]
    out += [f'  {n}: {v};' for n, v in light.items()]
    out += ['}', f".palette-swatch-{pid} {{ background: {hsl(h, 65 * k, 33)}; }}", '']
    return '\n'.join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, '..', '..', 'web', 'src', 'usherr-palettes.css')
    css = ['/* Generated by tools/usherr/palettes.py: edit that, not this. The colour',
           '   choices besides wine (Settings → General; PaletteChoice.tsx). */', '']
    css += [block(pid, h, s) for pid, (h, s) in PALETTES.items()]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(css))
    print('wrote', os.path.normpath(path), len(PALETTES), 'palettes')


if __name__ == '__main__':
    main()
